class TestPianoModel(unittest.TestCase):
    def test_standard_piano_has_88_keys_52_white_36_black(self):
        keys = piano_keys()
        self.assertEqual(PIANO_KEY_COUNT, 88)
        self.assertEqual(len(keys), 88)
        self.assertEqual(sum(k.is_white for k in keys), 52)
        self.assertEqual(sum(k.is_black for k in keys), 36)
        self.assertEqual(len({k.midi for k in keys}), 88)
        self.assertEqual([k.number for k in keys], list(range(1, 89)))

    def test_range_boundaries_and_reference_pitches(self):
        self.assertEqual((PIANO_LOWEST_MIDI, PIANO_HIGHEST_MIDI), (21, 108))
        lowest, highest = piano_keys()[0], piano_keys()[-1]
        self.assertEqual((lowest.midi, lowest.octave, lowest.pitch_class), (21, 0, 9))  # A0
        self.assertEqual((highest.midi, highest.octave, highest.pitch_class), (108, 8, 0))  # C8
        self.assertEqual(piano_key(60).number, 40)  # middle C is key 40
        self.assertEqual(piano_key(69).number, 49)  # A4 is key 49
        self.assertAlmostEqual(piano_key(69).frequency, 440.0)
        self.assertAlmostEqual(piano_key(60).frequency, 261.6255653, places=6)

    def test_ascending_and_descending_order(self):
        ascending = [k.midi for k in piano_keys()]
        self.assertEqual(ascending, list(range(21, 109)))
        self.assertEqual([k.midi for k in piano_keys(descending=True)], list(range(108, 20, -1)))

    def test_black_key_pattern_and_octaves(self):
        octave = [is_black_key(m) for m in range(60, 72)]
        self.assertEqual(octave, [False, True, False, True, False, False, True, False, True, False, True, False])
        self.assertEqual(piano_key(59).octave, 3)  # B3
        self.assertEqual(piano_key(60).octave, 4)  # C4
        self.assertEqual(piano_key(21).octave, 0)
        self.assertEqual(piano_key(24).octave, 1)  # C1

    def test_general_midi_domain_differs_from_piano_range(self):
        self.assertFalse(is_on_piano(20))
        self.assertFalse(is_on_piano(109))
        self.assertTrue(is_on_piano(21))
        self.assertIsNone(piano_key(0).number)
        self.assertIsNone(piano_key(127).number)

    def test_invalid_midi_values_are_rejected(self):
        for bad in (-1, 128, 60.0, "60", True, None):
            with self.subTest(bad=bad), self.assertRaises(PitchRangeError):
                piano_key(bad)

    def test_enharmonic_spellings_keep_sounding_pitch_across_octave_boundaries(self):
        spellings = piano_key(60).enharmonic_spellings()
        self.assertIn(NoteSpelling("C", 0, 4), spellings)
        self.assertIn(NoteSpelling("B", 1, 3), spellings)  # B#3 = 60
        self.assertIn(NoteSpelling("D", -2, 4), spellings)
        self.assertEqual(spellings[0], NoteSpelling("C", 0, 4))
        self.assertIn(NoteSpelling("C", -1, 4), piano_key(59).enharmonic_spellings())  # Cb4 = 59
        for midi in range(21, 109):
            for spelling in piano_key(midi).enharmonic_spellings():
                self.assertEqual(spelling.midi_number, midi)


class TestViewport(unittest.TestCase):
    def test_full_piano_viewport_and_white_key_edges(self):
        full = KeyboardViewport.full_piano()
        self.assertEqual(len(full.keys()), 88)
        self.assertEqual(len(full.white_keys()), 52)
        with self.assertRaises(PitchRangeError):
            KeyboardViewport(61, 84)  # black edge
        with self.assertRaises(PitchRangeError):
            KeyboardViewport(12, 48)  # below A0
        with self.assertRaises(PitchRangeError):
            KeyboardViewport(60, 64)  # less than an octave

    def test_shift_clamps_to_piano_and_keeps_width(self):
        viewport = KeyboardViewport(48, 84)
        self.assertEqual(viewport.shifted(12), KeyboardViewport(60, 96))
        self.assertEqual(viewport.shifted(-60).low, 21)
        top = viewport.shifted(60)
        self.assertLessEqual(top.high, 108)
        self.assertTrue(top.span >= 35)

    def test_partition_keeps_every_note(self):
        viewport = KeyboardViewport(60, 72)
        below, visible, above = viewport.partition([40, 60, 64, 67, 72, 76, 64])
        self.assertEqual((below, visible, above), ((40,), (60, 64, 67, 72), (76,)))

    def test_fit_moves_to_include_voicing(self):
        viewport = KeyboardViewport(60, 72)
        fitted = viewport.fitted_to([40, 47, 52])
        self.assertTrue(fitted.contains(40) and fitted.contains(52))
        self.assertIs(viewport.fitted_to([62, 64]), viewport)
        wide = KeyboardViewport(60, 72).fitted_to([30, 100])
        self.assertTrue(wide.contains(30) and wide.contains(100))


class TestNotationContract(unittest.TestCase):
    TABLE = (
        # (INT, DE, MIDI)
        ("B3", "H3", 59),
        ("Bb3", "B3", 58),
        ("Ab4", "As4", 68),
        ("C#4", "Cis4", 61),
        ("Db4", "Des4", 61),
        ("F#4", "Fis4", 66),
        ("Gb4", "Ges4", 66),
        ("B#3", "His3", 60),
        ("Cb4", "Ces4", 59),
        ("Ebb4", "Eses4", 62),
        ("F##4", "Fisis4", 67),
    )

    def test_int_and_de_names_map_to_the_same_key(self):
        for int_name, de_name, midi in self.TABLE:
            with self.subTest(int_name=int_name):
                int_spelling = parse_spelling(int_name, "INT")
                de_spelling = parse_spelling(de_name, "DE")
                self.assertEqual(int_spelling, de_spelling)
                self.assertEqual(int_spelling.midi_number, midi)
                self.assertEqual(int_spelling.render("DE"), de_name)
                self.assertIn(int_spelling, piano_key(midi).enharmonic_spellings())

    def test_spell_at_keeps_letter_and_moves_octave(self):
        self.assertEqual(spell_at(NoteSpelling("B", 1, 4), 60), NoteSpelling("B", 1, 3))
        self.assertEqual(spell_at(NoteSpelling("C", -1, 4), 71), NoteSpelling("C", -1, 5))
        with self.assertRaises(Exception):
            spell_at(NoteSpelling("C", 0, 4), 61)

    def test_key_labels_follow_context_not_midi(self):
        viewport = KeyboardViewport(60, 72)
        sharp = KeyboardLayers(spellings={61: NoteSpelling("C", 1, 4)})
        flat = KeyboardLayers(spellings={61: NoteSpelling("D", -1, 4)})
        self.assertEqual(build_view_model(viewport, sharp, "DE").visual(61).label, "Cis4")
        self.assertEqual(build_view_model(viewport, flat, "DE").visual(61).label, "Des4")
        self.assertEqual(build_view_model(viewport, KeyboardLayers(), "DE").visual(61).label, "")
        names = build_view_model(viewport, KeyboardLayers(), "DE", show_all_names=True).visual(61).label
        self.assertEqual(names, "Cis/Des")
        self.assertEqual(build_view_model(viewport, KeyboardLayers(), "DE").visual(71).label, "")
        self.assertEqual(build_view_model(viewport, KeyboardLayers(), "DE", show_all_names=True).visual(71).label, "H4")


class TestChordToneRoles(unittest.TestCase):
    GOLDEN = {
        # symbol: [(interval label, INT name, DE name), ...]
        "C": [("1", "C", "C"), ("3", "E", "E"), ("5", "G", "G")],
        "Cm": [("1", "C", "C"), ("b3", "Eb", "Es"), ("5", "G", "G")],
        "Ddim": [("1", "D", "D"), ("b3", "F", "F"), ("b5", "Ab", "As")],
        "Caug": [("1", "C", "C"), ("3", "E", "E"), ("#5", "G#", "Gis")],
        "G7": [("1", "G", "G"), ("3", "B", "H"), ("5", "D", "D"), ("b7", "F", "F")],
        "Dm7": [("1", "D", "D"), ("b3", "F", "F"), ("5", "A", "A"), ("b7", "C", "C")],
        "Cmaj7": [("1", "C", "C"), ("3", "E", "E"), ("5", "G", "G"), ("7", "B", "H")],
        "Bm7b5": [("1", "B", "H"), ("b3", "D", "D"), ("b5", "F", "F"), ("b7", "A", "A")],
        "Cdim7": [("1", "C", "C"), ("b3", "Eb", "Es"), ("b5", "Gb", "Ges"), ("bb7", "Bbb", "Heses")],
        "Csus2": [("1", "C", "C"), ("2", "D", "D"), ("5", "G", "G")],
        "Csus4": [("1", "C", "C"), ("4", "F", "F"), ("5", "G", "G")],
        "Cadd9": [("1", "C", "C"), ("3", "E", "E"), ("5", "G", "G"), ("9", "D", "D")],
        "C7#9": [("1", "C", "C"), ("3", "E", "E"), ("5", "G", "G"), ("b7", "Bb", "B"), ("#9", "D#", "Dis")],
        "C7b9": [("1", "C", "C"), ("3", "E", "E"), ("5", "G", "G"), ("b7", "Bb", "B"), ("b9", "Db", "Des")],
        "C7#11": [("1", "C", "C"), ("3", "E", "E"), ("5", "G", "G"), ("b7", "Bb", "B"), ("#11", "F#", "Fis")],
        "C13": [("1", "C", "C"), ("3", "E", "E"), ("5", "G", "G"), ("b7", "Bb", "B"), ("9", "D", "D"),
                ("13", "A", "A")],
        "Ebm7b5": [("1", "Eb", "Es"), ("b3", "Gb", "Ges"), ("b5", "Bbb", "Heses"), ("b7", "Db", "Des")],
    }

    def test_golden_chord_tone_roles_and_spellings(self):
        for symbol, expected in self.GOLDEN.items():
            with self.subTest(symbol=symbol):
                tones = chord_tones(parse_chord(symbol, "INT"))
                got = [(t.role.interval_label, t.name("INT"), t.name("DE")) for t in tones]
                self.assertEqual(got, expected)

    def test_every_supported_quality_on_every_root_has_roles_and_pitch_classes(self):
        roots = ("C", "Db", "D", "Eb", "E", "F", "F#", "G", "Ab", "A", "Bb", "B")
        for quality, template in CHORD_TEMPLATES.items():
            for root in roots:
                with self.subTest(quality=quality, root=root):
                    chord = parse_chord(root + quality, "INT")
                    tones = chord_tones(chord)
                    self.assertEqual({t.pitch_class for t in tones}, chord.pitch_class_set)
                    self.assertEqual(tones[0].role, ChordToneRole.ROOT)
                    self.assertEqual(len(tones), len(template["theoretical"]))
                    for tone in tones:
                        if tone.spelling is not None:
                            self.assertEqual(int(tone.spelling.pitch_class), tone.pitch_class)

    def test_dim7_seventh_and_sixth_chord_sixth_are_distinguished(self):
        dim7 = chord_tones(parse_chord("Cdim7", "INT"))
        six = chord_tones(parse_chord("C6", "INT"))
        self.assertEqual(dim7[-1].role, ChordToneRole.DIMINISHED_SEVENTH)
        self.assertEqual(six[-1].role, ChordToneRole.SIXTH)
        self.assertEqual(dim7[-1].pitch_class, six[-1].pitch_class)  # same key, different meaning

    def test_unsupported_quality_is_rejected_not_substituted(self):
        with self.assertRaises(ChordConstructionError):
            parse_chord("Cmaj7b9#11b13", "INT")

    def test_de_chord_symbols_reparse_to_the_same_chord(self):
        for symbol in ("Bb7", "B7", "F#m7b5", "Ab/C", "Ebmaj7", "C7#11", "Bbdim7"):
            with self.subTest(symbol=symbol):
                chord = parse_chord(symbol, "INT")
                german = render_chord_symbol(chord, "DE")
                self.assertEqual(parse_chord(german, "DE"), chord)
        self.assertEqual(render_chord_symbol(parse_chord("Bb7", "INT"), "DE"), "B7")
        self.assertEqual(render_chord_symbol(parse_chord("B7", "INT"), "DE"), "H7")
        self.assertEqual(render_chord_symbol(parse_chord("Ab/C", "INT"), "DE"), "As/C")


class TestGoldenVoicings(unittest.TestCase):
    """Reference voicings in German names (M3 of the keyboard assignment)."""

    GOLDEN = (
        ("C", (60, 64, 67), ("C4", "E4", "G4")),
        ("Cm", (60, 63, 67), ("C4", "Es4", "G4")),
        ("Am", (57, 60, 64), ("A3", "C4", "E4")),
        ("G7", (55, 59, 62, 65), ("G3", "H3", "D4", "F4")),
        ("Cmaj7", (60, 64, 67, 71), ("C4", "E4", "G4", "H4")),
        ("Dm7", (62, 65, 69, 72), ("D4", "F4", "A4", "C5")),
    )

    def test_golden_reference_voicings_label_root_bass_and_names(self):
        for symbol, midi, names in self.GOLDEN:
            with self.subTest(symbol=symbol):
                labelled = label_voicing(parse_chord(symbol, "INT"), midi)
                self.assertEqual(labelled.midi_notes, midi)
                self.assertEqual(tuple(n.name("DE") for n in labelled.notes), names)
                self.assertTrue(labelled.bass.is_root)
                self.assertEqual(labelled.inversion.inversion, ChordInversion.ROOT_POSITION)
                self.assertEqual(labelled.omitted_roles, ())

    def test_c_major_inversions_change_bass_but_keep_identity(self):
        chord = parse_chord("C", "INT")
        root = Voicing((60, 64, 67))
        cases = (
            (0, (60, 64, 67), "C4", ChordInversion.ROOT_POSITION, "5/3"),
            (1, (64, 67, 72), "E4", ChordInversion.FIRST_INVERSION, "6"),
            (2, (67, 72, 76), "G4", ChordInversion.SECOND_INVERSION, "6/4"),
        )
        for rotation, midi, bass, inversion, figure in cases:
            with self.subTest(rotation=rotation):
                labelled = label_voicing(chord, root.invert(rotation))
                self.assertEqual(labelled.midi_notes, midi)
                self.assertEqual(labelled.bass.name("DE"), bass)
                self.assertEqual(labelled.inversion.inversion, inversion)
                self.assertEqual(labelled.inversion.figured_bass, figure)
                self.assertEqual({n.midi % 12 for n in labelled.notes}, {0, 4, 7})
                self.assertEqual(labelled.bass.is_root, rotation == 0)

    def test_third_inversion_of_seventh_chord(self):
        labelled = label_voicing(parse_chord("G7", "INT"), Voicing((55, 59, 62, 65)).invert(3))
        self.assertEqual(labelled.bass.role, ChordToneRole.MINOR_SEVENTH)
        self.assertEqual(labelled.inversion.inversion, ChordInversion.THIRD_INVERSION)
        self.assertEqual(labelled.inversion.figured_bass, "4/2")

    def test_slash_chord_separates_root_and_bass(self):
        chord = parse_chord("C/E", "INT")
        voicing = chord.to_voicing(3, "CLOSE")
        labelled = label_voicing(chord, voicing)
        self.assertEqual(labelled.midi_notes, (52, 55, 60))  # E3 G3 C4
        self.assertFalse(labelled.bass.is_root)
        self.assertTrue(labelled.bass.is_bass)
        self.assertEqual(labelled.bass.role, ChordToneRole.MAJOR_THIRD)
        self.assertEqual(labelled.root_midis, (60,))

    def test_non_chord_slash_bass_keeps_written_spelling(self):
        chord = parse_chord("C/D", "INT")
        labelled = label_voicing(chord, (50, 60, 64, 67))
        self.assertEqual(labelled.bass.role, ChordToneRole.SLASH_BASS)
        self.assertEqual(labelled.bass.name("DE"), "D3")
        self.assertEqual(labelled.foreign_notes, ())
        self.assertEqual(labelled.inversion.figured_bass, "slash")

    def test_octave_doublings_keep_both_roots(self):
        labelled = label_voicing(parse_chord("F", "INT"), (41, 53, 57, 60))
        self.assertEqual(labelled.root_midis, (41, 53))
        self.assertEqual([n.is_bass for n in labelled.notes], [True, False, False, False])

    def test_drop2_and_shell_contracts(self):
        chord = parse_chord("Cmaj7", "INT")
        drop2 = label_voicing(chord, chord.to_voicing(3, "DROP2"))
        self.assertEqual(drop2.midi_notes, (43, 48, 52, 59))  # G2 C3 E3 H3
        self.assertEqual(drop2.bass.role, ChordToneRole.PERFECT_FIFTH)
        self.assertEqual(drop2.inversion.inversion, ChordInversion.SECOND_INVERSION)
        shell = label_voicing(parse_chord("G7", "INT"), parse_chord("G7", "INT").to_voicing(2, "SHELL"))
        self.assertEqual({n.role for n in shell.notes},
                         {ChordToneRole.ROOT, ChordToneRole.MAJOR_THIRD, ChordToneRole.MINOR_SEVENTH})
        self.assertIn(ChordToneRole.PERFECT_FIFTH, shell.omitted_roles)

    def test_unrealisable_voicings_fail_explicitly(self):
        with self.assertRaises(VoiceLeadingError):
            parse_chord("C", "INT").to_voicing(3, "DROP2")
        with self.assertRaises(VoiceLeadingError):
            Voicing((120, 124, 127)).invert(1)
        with self.assertRaises(ChordConstructionError):
            label_voicing(parse_chord("C", "INT"), ())


class TestScaleOverlay(unittest.TestCase):
    def test_c_major_chord_inside_c_major_scale_keeps_both_facts(self):
        chord = label_voicing(parse_chord("C", "INT"), (60, 64, 67))
        scale = construct_scale(parse_spelling("C", "INT"), "ionian")
        layers = KeyboardLayers(
            chord_notes={n.midi: n.role for n in chord.notes},
            chord_bass=60,
            scale_pitch_classes={int(s.pitch_class): i + 1 for i, s in enumerate(scale.spellings)},
            scale_spellings={int(s.pitch_class): s for s in scale.spellings},
        )
        model = build_view_model(KeyboardViewport(60, 72), layers, "INT")
        c, d, e, cs = model.visual(60), model.visual(62), model.visual(64), model.visual(61)
        self.assertEqual(c.states, {KeyState.CHORD_ROOT, KeyState.CHORD_BASS, KeyState.SCALE_ROOT})
        self.assertEqual((c.fill, c.outline), (KeyState.CHORD_ROOT, KeyState.SCALE_ROOT))
        self.assertEqual(c.badges, ("1", "B"))
        self.assertEqual((e.fill, e.outline), (KeyState.CHORD_TONE, KeyState.SCALE_TONE))
        self.assertEqual((d.fill, d.outline), (KeyState.SCALE_TONE, None))
        self.assertEqual(d.label, "D4")
        self.assertEqual(cs.states, frozenset())

    def test_supported_scales_spell_from_the_core(self):
        cases = {
            ("A", "aeolian"): ["A", "B", "C", "D", "E", "F", "G"],
            ("A", "harmonic_minor"): ["A", "B", "C", "D", "E", "F", "G#"],
            ("A", "melodic_minor"): ["A", "B", "C", "D", "E", "F#", "G#"],
            ("D", "dorian"): ["D", "E", "F", "G", "A", "B", "C"],
            ("C", "blues"): ["C", "Eb", "F", "F#", "G", "Bb"],
            ("C", "major_pentatonic"): ["C", "D", "E", "G", "A"],
        }
        for (root, name), expected in cases.items():
            with self.subTest(scale=name):
                scale = construct_scale(parse_spelling(root, "INT"), name)
                self.assertEqual([s.render("INT")[:-1] for s in scale.spellings], expected)


class TestStatePriority(unittest.TestCase):
    def test_overlapping_states_are_all_kept_and_fill_follows_priority(self):
        layers = KeyboardLayers(
            chord_notes={60: ChordToneRole.ROOT}, chord_bass=60,
            scale_pitch_classes={0: 1}, pressed=frozenset({60}), practice_correct=frozenset({60}),
        )
        states = states_for(60, layers)
        self.assertEqual(states, {
            KeyState.CHORD_ROOT, KeyState.CHORD_BASS, KeyState.SCALE_ROOT, KeyState.PRESSED,
            KeyState.PRACTICE_CORRECT,
        })
        self.assertEqual(resolve_fill(states), KeyState.PRACTICE_CORRECT)
        self.assertEqual(resolve_outline(states, KeyState.PRACTICE_CORRECT), KeyState.SCALE_ROOT)
        visual = build_view_model(KeyboardViewport(60, 72), layers, "INT").visual(60)
        self.assertIn("1", visual.badges)
        self.assertIn("B", visual.badges)
        self.assertIn("✓", visual.badges)
        self.assertIn("PRESSED", visual.description)

    def test_fill_priority_is_total_and_deterministic(self):
        self.assertEqual(len(FILL_PRIORITY), len(set(FILL_PRIORITY)))
        self.assertNotIn(KeyState.CHORD_BASS, FILL_PRIORITY)  # bass is a marker, never hidden by fill
        for index, state in enumerate(FILL_PRIORITY):
            lower = set(FILL_PRIORITY[index:])
            self.assertEqual(resolve_fill(lower), state)

    def test_notes_outside_viewport_and_piano_are_reported(self):
        layers = KeyboardLayers(chord_notes={10: ChordToneRole.ROOT, 40: ChordToneRole.MAJOR_THIRD,
                                             64: ChordToneRole.PERFECT_FIFTH, 100: ChordToneRole.ROOT})
        model = build_view_model(KeyboardViewport(60, 72), layers, "INT")
        self.assertEqual(model.hidden_below, (40,))
        self.assertEqual(model.hidden_above, (100,))
        self.assertEqual(model.off_piano, (10,))
        self.assertEqual(layers.musical_notes(), (10, 40, 64, 100))


